export const DEFAULT_LANGUAGE_CODE = 'en-IN';

export function getLanguageByCode(code) {
  if (!code) return SUPPORTED_LANGUAGES[0];
  const normalized = code.trim().toLowerCase();
  return (
    SUPPORTED_LANGUAGES.find(l => l.code.toLowerCase() === normalized) ||
    SUPPORTED_LANGUAGES.find(l => l.name.toLowerCase() === normalized) ||
    SUPPORTED_LANGUAGES[0]
  );
}

export function getLanguageByLegacyName(name) {
  if (!name) return SUPPORTED_LANGUAGES[0];
  const clean = name.split(' ')[0].trim().toLowerCase();
  return (
    SUPPORTED_LANGUAGES.find(l => l.name.toLowerCase() === clean) ||
    SUPPORTED_LANGUAGES.find(l => l.code.toLowerCase() === clean) ||
    SUPPORTED_LANGUAGES[0]
  );
}
